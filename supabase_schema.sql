create table if not exists public.cards (
  id text primary key default gen_random_uuid()::text,
  name text not null,
  type text,
  image text,
  description text,
  hp integer,
  attacks jsonb,
  defense jsonb,
  special jsonb,
  sounds jsonb,
  active boolean default true,
  "createdAt" text,
  region text,
  fact text,
  emoji text
);

create table if not exists public.admins (
  id text primary key default gen_random_uuid()::text,
  username text not null,
  password text not null
);

create table if not exists public.players (
  id bigint generated by default as identity primary key,
  nickname text not null,
  avatar text,
  points integer default 0,
  wins integer default 0,
  losses integer default 0,
  "gamesPlayed" integer default 0,
  "createdAt" text
);

create table if not exists public.battles (
  id bigint generated by default as identity primary key,
  "playerId" bigint,
  "playerNickname" text,
  result text,
  "pointsAwarded" integer,
  "playerDeck" jsonb,
  "machineDeck" jsonb,
  "startedAt" text,
  "endedAt" text
);

grant all on public.cards, public.admins, public.players, public.battles to anon;

alter table public.cards enable row level security;
alter table public.admins enable row level security;
alter table public.players enable row level security;
alter table public.battles enable row level security;

drop policy if exists "anon_all_cards" on public.cards;
create policy "anon_all_cards" on public.cards for all to anon using (true) with check (true);

drop policy if exists "anon_all_admins" on public.admins;
create policy "anon_all_admins" on public.admins for all to anon using (true) with check (true);

drop policy if exists "anon_all_players" on public.players;
create policy "anon_all_players" on public.players for all to anon using (true) with check (true);

drop policy if exists "anon_all_battles" on public.battles;
create policy "anon_all_battles" on public.battles for all to anon using (true) with check (true);
